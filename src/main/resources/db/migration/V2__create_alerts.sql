CREATE TABLE alerts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id     BIGINT        NOT NULL REFERENCES readings (id),
    device_id      BIGINT        NOT NULL REFERENCES devices (id),
    status         VARCHAR(20)   NOT NULL,
    ai_category    VARCHAR(50),
    ai_urgency     VARCHAR(20),
    ai_explanation VARCHAR(1000),
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_alerts_reading UNIQUE (reading_id),
    CONSTRAINT ck_alerts_status  CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    CONSTRAINT ck_alerts_urgency CHECK (ai_urgency IN ('LOW', 'MEDIUM', 'CRITICAL'))
);

-- Serves GET /api/alerts?status=... newest first (issue #23)
CREATE INDEX ix_alerts_status_created ON alerts (status, created_at DESC);
