CREATE TABLE devices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    location    VARCHAR(200),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE thresholds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id   BIGINT           NOT NULL REFERENCES devices (id),
    metric      VARCHAR(20)      NOT NULL,
    min_value   DOUBLE PRECISION NOT NULL,
    max_value   DOUBLE PRECISION NOT NULL,
    CONSTRAINT ck_thresholds_metric  CHECK (metric IN ('TEMPERATURE', 'HUMIDITY', 'VIBRATION')),
    CONSTRAINT ck_thresholds_min_max CHECK (min_value <= max_value),
    CONSTRAINT uq_thresholds_device_metric UNIQUE (device_id, metric)
);

CREATE TABLE readings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id   BIGINT           NOT NULL REFERENCES devices (id),
    metric      VARCHAR(20)      NOT NULL,
    value       DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ      NOT NULL,
    CONSTRAINT ck_readings_metric CHECK (metric IN ('TEMPERATURE', 'HUMIDITY', 'VIBRATION'))
);

CREATE INDEX ix_readings_device_metric_time ON readings (device_id, metric, recorded_at);